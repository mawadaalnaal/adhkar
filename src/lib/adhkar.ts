function sortItemsByOrder(items: DhikrCategory["items"], order: string[]) {
  const orderIndex = new Map<string, number>(order.map((id, idx) => [id, idx]));
  const decorated = items.map((item, idx) => ({ item, idx }));
  decorated.sort((a, b) => {
    const aOrder = orderIndex.get(a.item.id);
    const bOrder = orderIndex.get(b.item.id);
    const aRank = aOrder === undefined ? Number.POSITIVE_INFINITY : aOrder;
    const bRank = bOrder === undefined ? Number.POSITIVE_INFINITY : bOrder;
    if (aRank !== bRank) return aRank - bRank;
    return a.idx - b.idx;
  });
  return decorated.map((d) => d.item);
}

export const dhikrCategories: DhikrCategory[] = allDhikrCategories
  .filter((c) => c.slug !== "ruqyah-medium" && c.slug !== "ruqyah-long")
  .map((c) => {
    const order = itemOrderBySlug[c.slug];
    if (!order) return c;
    return { ...c, items: sortItemsByOrder(c.items, order) };
  })
  .sort((a, b) => {
  const order = ["morning", "evening", "after-prayer", "sleep", "ruqyah-brief", "duas"];
  const aIndex = order.indexOf(a.slug);
  const bIndex = order.indexOf(b.slug);
  const aRank = aIndex === -1 ? Number.POSITIVE_INFINITY : aIndex;
  const bRank = bIndex === -1 ? Number.POSITIVE_INFINITY : bIndex;
  if (aRank !== bRank) return aRank - bRank;
  return 0;
  });

export function getCategoryBySlug(slug: string): DhikrCategory | undefined {
  return dhikrCategories.find((c) => c.slug === slug);
}

export function getDhikrById(id: string): (Dhikr & { category: DhikrCategory }) | undefined {
  for (const category of dhikrCategories) {
    const item = category.items.find((i) => i.id === id);
    if (item) return { ...item, category };
  }
  return undefined;
}
